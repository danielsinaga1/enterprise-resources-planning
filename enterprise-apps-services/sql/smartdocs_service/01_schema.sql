-- =====================================================================
-- SmartDocs — skema db_smartdocs (PostgreSQL)
-- ---------------------------------------------------------------------
-- Hasil konversi dump MariaDB `smartdocs_db` milik aplikasi SmartDocs.
-- Server KPI PostgreSQL-only sejak MySQL dihapus 2026-07-11, jadi tipe
-- MySQL dipetakan ulang: int(11) -> integer, tinyint(1) -> boolean,
-- decimal -> numeric, timestamp -> timestamptz, longtext berisi JSON ->
-- jsonb.
--
-- Kolom *_json sengaja jsonb, bukan text: dump aslinya sudah memasang
-- CHECK json_valid(), dan dashboard/laporan perlu membaca field di
-- dalamnya (mis. validation_json->>'status') tanpa parsing di aplikasi.
--
-- Kolom tanggal invoice tetap varchar — nilainya teks mentah hasil OCR
-- yang sering bukan tanggal sama sekali ("1 CreamBruille 14"), jadi
-- memaksanya jadi DATE akan membuang data dan menggagalkan impor.
--
-- Jalankan sebagai: psql -d db_smartdocs -f 01_schema.sql
-- =====================================================================

BEGIN;

DROP TABLE IF EXISTS activity_logs   CASCADE;
DROP TABLE IF EXISTS document_items  CASCADE;
DROP TABLE IF EXISTS documents       CASCADE;
DROP TABLE IF EXISTS smartdocs_users CASCADE;

-- ---------------------------------------------------------------------
-- documents — satu baris per dokumen hasil OCR
-- ---------------------------------------------------------------------
CREATE TABLE documents (
    id                      integer        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vendor_name             varchar(255)   NOT NULL,
    activity_name           varchar(255)   DEFAULT 'Transaksi Umum',
    invoice_number          varchar(100),
    invoice_date            varchar(100),
    grand_total             numeric(15,2)  NOT NULL DEFAULT 0.00,
    created_at              timestamptz    NOT NULL DEFAULT now(),
    no_invoice              varchar(100)   DEFAULT '',
    division                varchar(100)   DEFAULT '',
    category                varchar(100)   DEFAULT '',
    payment_method          varchar(100)   DEFAULT '',
    description             text,
    due_date                varchar(50)    DEFAULT '',
    currency                varchar(10)    DEFAULT 'IDR',
    tax                     numeric(14,2)  DEFAULT 0.00,
    discount                numeric(14,2)  DEFAULT 0.00,
    confidence_json         jsonb,
    validation_json         jsonb,
    source_filename         varchar(255)   DEFAULT '',
    document_structure_json jsonb,
    source_file_path        varchar(500)   DEFAULT '',
    source_mime_type        varchar(100)   DEFAULT '',
    customer_name           varchar(255)   DEFAULT '',
    address                 text,
    city                    varchar(100)   DEFAULT '',
    phone                   varchar(100)   DEFAULT '',
    subtotal                numeric(14,2)  DEFAULT 0.00,
    note                    text           DEFAULT ''
);

COMMENT ON TABLE  documents                         IS 'Dokumen (invoice/struk) hasil pemindaian OCR SmartDocs.';
COMMENT ON COLUMN documents.invoice_date            IS 'Teks mentah hasil OCR, belum tentu tanggal yang sah.';
COMMENT ON COLUMN documents.confidence_json         IS 'Skor keyakinan OCR per field header.';
COMMENT ON COLUMN documents.validation_json         IS 'Hasil pemeriksaan aritmetika dan kelengkapan; berisi status tinjauan.';
COMMENT ON COLUMN documents.document_structure_json IS 'Struktur dokumen lengkap: field, tabel terdeteksi, ringkasan, teks mentah.';
COMMENT ON COLUMN documents.source_file_path        IS 'Nama berkas tersimpan di penyimpanan dokumen, bukan path absolut.';

-- ---------------------------------------------------------------------
-- document_items — baris tabel barang di dalam satu dokumen
-- ---------------------------------------------------------------------
CREATE TABLE document_items (
    id              integer        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id     integer        NOT NULL
                                   REFERENCES documents (id) ON DELETE CASCADE,
    item_name       varchar(255)   NOT NULL,
    quantity        integer        DEFAULT 1,
    price           numeric(15,2)  DEFAULT 0.00,
    total_price     numeric(15,2)  DEFAULT 0.00,
    unit            varchar(50)    DEFAULT '',
    confidence_json jsonb,
    validation_json jsonb
);

CREATE INDEX idx_document_items_document ON document_items (document_id);

COMMENT ON TABLE  document_items                 IS 'Baris barang/jasa pada dokumen, hasil pembacaan tabel oleh OCR.';
COMMENT ON COLUMN document_items.validation_json IS 'Pemeriksaan per baris: jumlah x harga = total.';

-- ---------------------------------------------------------------------
-- activity_logs — jejak aktivitas pengguna atas dokumen
-- ---------------------------------------------------------------------
CREATE TABLE activity_logs (
    id          integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_action varchar(255) NOT NULL,
    document_id integer      REFERENCES documents (id) ON DELETE CASCADE,
    timestamp   timestamptz  NOT NULL DEFAULT now(),
    username    varchar(100) DEFAULT 'System',
    user_id     integer
);

CREATE INDEX idx_activity_logs_document  ON activity_logs (document_id);
CREATE INDEX idx_activity_logs_timestamp ON activity_logs ("timestamp" DESC);

COMMENT ON TABLE  activity_logs         IS 'Jejak aktivitas SmartDocs (unggah, simpan, ubah, hapus).';
COMMENT ON COLUMN activity_logs.user_id IS 'Id pengguna IRMS untuk baris baru; baris lama memakai id pengguna SmartDocs lama.';

-- ---------------------------------------------------------------------
-- smartdocs_users — pengguna aplikasi SmartDocs lama
-- ---------------------------------------------------------------------
-- Login modul ini memakai autentikasi IRMS (LDAP + RBAC), jadi tabel ini
-- TIDAK dipakai untuk masuk aplikasi. Disimpan hanya agar username pada
-- activity_logs lama tetap bisa ditelusuri. Kolom password ikut dibawa
-- apa adanya (hash bcrypt) dan tidak pernah dibaca aplikasi baru.
CREATE TABLE smartdocs_users (
    id            integer      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      varchar(100) NOT NULL UNIQUE,
    email         varchar(255) NOT NULL UNIQUE,
    password      varchar(255) NOT NULL,
    role          varchar(50)  NOT NULL DEFAULT 'User',
    created_at    timestamptz  NOT NULL DEFAULT now(),
    display_name  varchar(100),
    profile_photo text,
    is_active     boolean      NOT NULL DEFAULT true
);

COMMENT ON TABLE smartdocs_users IS 'Arsip pengguna SmartDocs lama; autentikasi modul memakai IRMS, tabel ini tidak dipakai untuk login.';

COMMIT;
